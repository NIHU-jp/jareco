#!/usr/bin/env python3
"""Apply an explicit experimental type policy and preserve legacy content types."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from jpcoar_ssg.metadata import DC, JPCOAR, local, namespace, parse_xml, read_records

EXTENSION = 'urn:jpcoar-static-catalogue:1'
RDF_RESOURCE = '{http://www.w3.org/1999/02/22-rdf-syntax-ns#}resource'


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def classify(source, policy_path, corrections_path, report_path):
    raw, policy_raw = source.read_bytes(), policy_path.read_bytes()
    policy = json.loads(policy_raw)
    corrections = json.loads(corrections_path.read_text(encoding='utf-8'))
    if corrections['corrected_sha256'] != digest(raw):
        raise ValueError('Input differs from the correction log; reconcile provenance first')
    previous = json.loads(report_path.read_text(encoding='utf-8')) if report_path.exists() else {}
    if previous.get('output_sha256') == digest(raw) and previous.get('policy_sha256') == digest(policy_raw):
        return previous
    root, _ = parse_xml(raw)
    parents = {c: p for p in root.iter() for c in p}
    nodes = []
    for node in root.iter():
        if local(node.tag) != 'jpcoar' or namespace(node.tag) not in JPCOAR:
            continue
        p = parents.get(node)
        while p is not None and local(p.tag) != 'record':
            p = parents.get(p)
        if p is not None and any(local(h.tag) == 'header' and h.get('status') == 'deleted' for h in p):
            continue
        if p is None:
            raise ValueError('Classification requires a record wrapper for local contentType metadata')
        nodes.append((node, p))
    records, _ = read_records(source)
    if len(nodes) != len(records):
        raise ValueError('Record reconciliation failed')
    exceptions = {}
    notes = {item['record']: item for item in policy.get('review_notes', [])}
    for rule in policy['exceptions']:
        if rule['record'] in exceptions or not 1 <= rule['record'] <= len(records):
            raise ValueError('Duplicate or out-of-range classification exception')
        if records[rule['record'] - 1]['titles'][0]['value'] != rule['title']:
            raise ValueError('Exception title does not match its record; policy needs review')
        if rule['type'] not in policy['types']:
            raise ValueError('Unsupported exception type')
        exceptions[rule['record']] = rule
    if policy['default_type'] not in policy['types']:
        raise ValueError('Unsupported default type')
    changes, assignments = [], []
    counts = Counter()
    migrated = 0
    for index, ((node, wrapper), record) in enumerate(zip(nodes, records), 1):
        rule = exceptions.get(index)
        chosen = rule['type'] if rule else policy['default_type']
        uri = policy['types'][chosen]
        old_types = list(node.findall('{' + DC + '}type'))
        for old in old_types:
            value = (old.text or '').strip()
            # On a rerun, do not migrate the classification already generated by us.
            if value in policy['types'] and old.get(RDF_RESOURCE) == policy['types'][value]:
                continue
            extension_tag = '{' + EXTENSION + '}contentType'
            if value and not any((e.text or '') == value for e in wrapper.findall(extension_tag)):
                retained = ET.SubElement(wrapper, extension_tag, sourceField='dc:type')
                retained.text = value
                migrated += 1
                changes.append(dict(record=index, title=record['titles'][0]['value'], action='preserve_legacy_content_type',
                                    before=value, after={'contentType': value, 'namespace': EXTENSION}))
        before = [{'value': n.text, 'attributes': dict(n.attrib)} for n in old_types]
        for old in old_types:
            node.remove(old)
        new = ET.Element('{' + DC + '}type', {RDF_RESOURCE: uri})
        new.text = chosen
        # dc:type follows dc:language and precedes versions/identifiers/relations.
        later = {'version', 'identifier', 'identifierRegistration', 'relation', 'temporal', 'geoLocation',
                 'fundingReference', 'sourceIdentifier', 'edition', 'volumeTitle', 'originalLanguage', 'extent',
                 'format', 'holdingAgent', 'datasetSeries', 'sourceTitle', 'volume', 'issue', 'numPages',
                 'pageStart', 'pageEnd', 'dissertationNumber', 'degreeName', 'dateGranted', 'degreeGrantor',
                 'conference', 'file', 'catalog'}
        position = next((i for i, child in enumerate(node) if local(child.tag) in later), len(node))
        node.insert(position, new)
        counts[chosen] += 1
        changes.append(dict(record=index, title=record['titles'][0]['value'], action='assign_experimental_resource_type',
                            before=before, after={'value': chosen, 'rdf:resource': uri}, policy=policy['id'],
                            basis='reviewed_exception' if rule else 'provisional_default'))
        assignments.append(dict(record=index, record_id=record['id'], title=record['titles'][0]['value'],
                                type=chosen, uri=uri, basis='reviewed_exception' if rule else 'provisional_default',
                                evidence=rule or None, review_note=notes.get(index),
                                content_types=[e.text for e in wrapper.findall('{' + EXTENSION + '}contentType')]))
    for prefix, ns in {'jpcoar':'https://github.com/JPCOAR/schema/blob/master/2.0/', 'dc':DC,
                       'dcterms':'http://purl.org/dc/terms/', 'datacite':'https://schema.datacite.org/meta/kernel-4/',
                       'rdf':'http://www.w3.org/1999/02/22-rdf-syntax-ns#', 'sc':EXTENSION}.items():
        ET.register_namespace(prefix, ns)
    ET.indent(root, space='  ')
    updated = ET.tostring(root, encoding='utf-8', xml_declaration=True) + b'\n'
    report = dict(policy=policy['id'], policy_sha256=digest(policy_raw), experimental=True,
                  input_sha256=digest(raw), output_sha256=digest(updated), type_counts=dict(counts),
                  migrated_content_type_values=migrated, assignments=assignments)
    corrections['corrected_sha256'] = digest(updated)
    corrections['policy'] = 'Experimental SSG derivative: conservative format repairs, approved broad DDC additions, and provisional resource types with legacy content labels retained separately. The original distribution remains unchanged.'
    corrections['changes'].extend(changes)
    for action in ('preserve_legacy_content_type', 'assign_experimental_resource_type'):
        corrections['correction_counts'][action] = corrections['correction_counts'].get(action, 0) + sum(c['action'] == action for c in changes)
    corrections['classification_policy'] = {'file':policy_path.name, 'sha256':digest(policy_raw), 'id':policy['id']}
    resolved = ('Missing required dc:type', 'dc:type lacks rdf:resource', 'Multiple dc:type')
    remaining = []
    for issue in corrections.get('unresolved', []):
        issues = [s for s in issue['issues'] if not s.startswith(resolved)]
        if issues:
            remaining.append(dict(issue, issues=issues))
    corrections['unresolved'] = remaining
    source.write_bytes(updated)
    for path, data in ((corrections_path, corrections), (report_path, report)):
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=ROOT / 'data/resources.xml')
    parser.add_argument('--policy', type=Path, default=ROOT / 'data/resource-type-policy.json')
    parser.add_argument('--corrections', type=Path, default=ROOT / 'data/corrections.json')
    parser.add_argument('--report', type=Path, default=ROOT / 'data/resource-type-assignments.json')
    args = parser.parse_args()
    report = classify(args.input, args.policy, args.corrections, args.report)
    print(json.dumps({'type_counts':report['type_counts'], 'migrated_content_type_values':report['migrated_content_type_values']}))


if __name__ == '__main__':
    main()
